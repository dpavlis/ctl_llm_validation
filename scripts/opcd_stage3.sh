#!/bin/bash -l
# Canonical Stage 3 on a new base (spec/belief_durability_plan.md A1/A2): OPCD stage 3a (40 rounds, fresh adapter) then 3b
# (16 rounds, belief-focused), then the gates, on GPUs 1 (training, eval server :3012) and 3 (sampler :3011).
#
#   setsid nohup scripts/opcd_stage3.sh /home/pavlisd/exports/qwen38_rb1010a_sftdpo rb1010a > logs/evals/stage3_rb1010a.log 2>&1 &
#   scripts/opcd_stage3.sh BASE_EXPORT TAG --dry-run     # write the configs, prepare, check the anchor; no GPU work
#
# TAG names the base: it becomes the vLLM served-model name and the run names s3a-TAG / s3b-TAG (no "_" allowed: the run
# script splits adapter names on it). Configs are generated from configs/opcd_stage3{a,b}.yaml (written for rb1009).
# A2: the belief prompts (target, contrast, hard sets 1-3) must be >= 30% of each stage's non-replay prompt weight.
set -euo pipefail
cd /home/pavlisd/llama_train
BASE=$1; TAG=$2; DRY=${3:-}
[[ "$TAG" == *_* ]] && { echo "TAG must not contain '_'"; exit 1; }
[ -f "$BASE/config.json" ] || { echo "no model at $BASE"; exit 1; }
PY=~/venv/bin/python; L=logs/evals; K=$L/locks; mkdir -p $K
A=s3a-$TAG; B=s3b-$TAG
for s in a b; do
  sed -e "s#^run: s3$s-rb1009#run: s3$s-$TAG#" -e "s#^base_model: .*#base_model: $BASE#" \
      -e "s#served_model: rb1009#served_model: $TAG#" -e "s#data/opcd/s3a-rb1009/round_039#data/opcd/$A/round_039#" \
      -e "1i # GENERATED by scripts/opcd_stage3.sh from configs/opcd_stage3$s.yaml for $TAG ($BASE)" \
      configs/opcd_stage3$s.yaml > configs/opcd_s3$s-$TAG.yaml
  grep -q "^run: s3$s-$TAG" configs/opcd_s3$s-$TAG.yaml && grep -q "served_model: $TAG" configs/opcd_s3$s-$TAG.yaml \
    || { echo "config s3$s-$TAG not rewritten"; exit 1; }
  CUDA_VISIBLE_DEVICES="" $PY opcd.py prepare --config configs/opcd_s3$s-$TAG.yaml > $L/stage3_prepare_s3$s-$TAG.log 2>&1
  $PY - "data/opcd/s3$s-$TAG/prompts.jsonl" <<'EOF'
import json, sys
P = [json.loads(l) for l in open(sys.argv[1])]
pool = [p for p in P if p["set"] in ("target", "hard", "contrast")]
w = lambda p: int(p.get("weight") or 1)
belief = sum(w(p) for p in pool if p["set"] in ("target", "contrast") or str(p.get("record_id", "")).startswith("opcd_hard"))
share = belief / sum(w(p) for p in pool)
print(f"{sys.argv[1]}: belief share of non-replay prompt weight {share:.2f}")
sys.exit(0 if share >= 0.30 else 1)
EOF
done
[ "$DRY" = "--dry-run" ] && { echo "dry run: configs/opcd_$A.yaml, configs/opcd_$B.yaml prepared"; exit 0; }

# vLLM: sampler on :3011 (GPU 3) and, after training, the eval server on :3012 (GPU 1), both serving BASE as TAG
for p in 3011 3012; do
  src=logs/evals/opcd_vllm_serve.sh; [ $p = 3012 ] && src=scripts/vllm_eval_serve.sh
  sed -e "s#--model /home/pavlisd/exports/qwen38_rb1006_sftdpo --served-model-name rb1006#--model $BASE --served-model-name $TAG#" \
      -e 's/ --lora-modules smoke=[^ ]*//' $src > $L/vllm_${p}_$TAG.sh
  grep -q "served-model-name $TAG" $L/vllm_${p}_$TAG.sh || { echo "serve script $p not rewritten"; exit 1; }
done
chmod +x $L/vllm_3012_$TAG.sh
curl -sf 127.0.0.1:3011/v1/models | grep -q "\"$TAG\"" || { setsid nohup bash $L/vllm_3011_$TAG.sh > $L/vllm_3011_$TAG.log 2>&1 < /dev/null & disown; }
until curl -sf 127.0.0.1:3011/v1/models | grep -q "\"$TAG\""; do sleep 10; done

echo "$(date '+%m-%d %H:%M') $A train (GPU 1)"
flock $K/gpu1.lock env CUDA_VISIBLE_DEVICES=1 $PY -u opcd.py train --config configs/opcd_$A.yaml > $L/opcd_${A}_train.log 2>&1 \
  || { echo "$A train failed"; exit 1; }
echo "$(date '+%m-%d %H:%M') $A train done; $B train + gates"
EVAL_SERVE=$L/vllm_3012_$TAG.sh GAPS=T44,T46,T53,T54,T57,T60,T61,T62,T63,T67,T73 scripts/opcd_gaps_run.sh $B 015
